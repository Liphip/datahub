#!/bin/sh
set -eu
export DB_PASSWORD="$(cat /keys/db-password)"
export CONNECTOR_CONFIG_KEY="$(cat /keys/connector.key)"
export DATATURNTABLE_PIPELINE_DATA_JDBC_PASSWORD="$(cat /keys/pipeline-password)"
export DATATURNTABLE_GRAFANA_DASHBOARD_ADMIN_PASSWORD="$(cat /keys/grafana-password)"
export DATATURNTABLE_GRAFANA_DASHBOARD_DATASOURCE_PASSWORD="$DATATURNTABLE_PIPELINE_DATA_JDBC_PASSWORD"
if [ "${DATATURNTABLE_OIDC_ENABLED:-false}" = true ]; then
  export DATATURNTABLE_OIDC_CLIENT_SECRET="$(cat /keys/oidc-client-secret)"
  export QUARKUS_OIDC_EXTERNAL_AUTHENTICATION_STATE_SECRET="$DATATURNTABLE_OIDC_CLIENT_SECRET"
  export QUARKUS_OIDC_EXTERNAL_TOKEN_STATE_MANAGER_ENCRYPTION_SECRET="$DATATURNTABLE_OIDC_CLIENT_SECRET"
fi
exec java ${JAVA_OPTS:--XX:MaxRAMPercentage=70} -jar /app/quarkus-run.jar
