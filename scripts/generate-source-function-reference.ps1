<#
.SYNOPSIS
Builds the checked-in declaration-level source reference.

.DESCRIPTION
Scans Kotlin and TypeScript/TSX source files (including tests) and creates a
Markdown inventory of classes, interfaces, types, enums, functions, and named
arrow functions. The generated descriptions use consistent verb-based wording;
the owning-file responsibility is maintained in docs/development/source-reference.md.

Run from any directory:
  powershell -ExecutionPolicy Bypass -File scripts/generate-source-function-reference.ps1
#>
[CmdletBinding()]
param(
    [string]$RepositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot ".."))
)

$ErrorActionPreference = 'Stop'
$outputPath = Join-Path $RepositoryRoot 'docs/development/source-function-reference.md'
$sourceRoots = @(
    (Join-Path $RepositoryRoot 'backend/src')
    (Join-Path $RepositoryRoot 'frontend/src')
)

function Escape-Markdown([string]$value) {
    return $value.Replace('|', '\|').Replace('`', '\`')
}

function Describe-Declaration([string]$name, [string]$kind, [bool]$isTest) {
    if ($kind -ne 'function') {
        return "Defines the $kind contract used by this source unit."
    }

    $subject = if ($isTest) { 'Verifies the named behavior.' } else { 'Implements the named behavior for this source unit.' }
    $patterns = @(
        @{ Regex = '^(list|find|get|load|read|query)'; Text = 'Retrieves or enumerates the requested state.' },
        @{ Regex = '^(create|register|add|insert|persist|save)'; Text = 'Creates or persists the requested state.' },
        @{ Regex = '^(update|patch|set|replace)'; Text = 'Updates the requested state.' },
        @{ Regex = '^(delete|remove|destroy|disconnect|stop)'; Text = 'Removes, stops, or releases the requested state.' },
        @{ Regex = '^(parse|deserialize|decode)'; Text = 'Parses external or persisted input into the required representation.' },
        @{ Regex = '^(serialize|encode|to[A-Z])'; Text = 'Converts a value into the representation required by its caller.' },
        @{ Regex = '^(validate|require|normalize|sanitize)'; Text = 'Validates or normalizes input before the caller continues.' },
        @{ Regex = '^(is|has|can|should|owns|requires)'; Text = 'Evaluates the named capability or state predicate.' },
        @{ Regex = '^(start|onStart|initialize|init|connect|spawn|acquire)'; Text = 'Initializes, connects, or acquires the named runtime resource.' },
        @{ Regex = '^(dispatch|send|publish|emit|write|route)'; Text = 'Delivers or routes the named data to its configured destination.' },
        @{ Regex = '^(handle|process|execute|run|evaluate)'; Text = 'Processes the named request, event, or operation.' }
    )
    foreach ($pattern in $patterns) {
        if ($name -match $pattern.Regex) { return $pattern.Text }
    }
    return $subject
}

$entries = [System.Collections.Generic.List[object]]::new()
foreach ($root in $sourceRoots) {
    if (-not (Test-Path $root)) { continue }
    Get-ChildItem -Path $root -Recurse -File -Include '*.kt', '*.ts', '*.tsx' | Sort-Object FullName | ForEach-Object {
        $file = $_
        $relative = [IO.Path]::GetRelativePath($RepositoryRoot, $file.FullName).Replace('\', '/')
        $isTest = $relative -match '(/test/|/__tests__/|\.test\.)'
        $lines = Get-Content -LiteralPath $file.FullName
        for ($index = 0; $index -lt $lines.Count; $index++) {
            $line = $lines[$index].Trim()
            $match = [regex]::Match($line, '^(?:public |private |protected |internal |export |default |abstract |open |data |sealed |final |async |suspend )*(class|interface|object|enum class|type)\s+([A-Za-z_][A-Za-z0-9_]*)')
            if ($match.Success) {
                $entries.Add([pscustomobject]@{ File=$relative; Line=$index+1; Name=$match.Groups[2].Value; Kind=$match.Groups[1].Value; Test=$isTest })
                continue
            }
            $match = [regex]::Match($line, '^(?:public |private |protected |internal |export |default |async |suspend )*fun\s+(?:[A-Za-z_][A-Za-z0-9_]*\.)?([A-Za-z_][A-Za-z0-9_]*)\s*\(')
            if (-not $match.Success) {
                $match = [regex]::Match($line, '^(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(')
            }
            if (-not $match.Success) {
                $match = [regex]::Match($line, '^(?:export\s+)?(?:const|let)\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?:async\s*)?(?:\([^)]*\)|[A-Za-z_][A-Za-z0-9_]*)\s*=>')
            }
            if ($match.Success) {
                $entries.Add([pscustomobject]@{ File=$relative; Line=$index+1; Name=$match.Groups[1].Value; Kind='function'; Test=$isTest })
            }
        }
    }
}

$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('# Source Function Reference')
[void]$builder.AppendLine()
[void]$builder.AppendLine('> Generated by `scripts/generate-source-function-reference.ps1`; do not edit by hand.')
[void]$builder.AppendLine()
[void]$builder.AppendLine("Generated from $($entries.Count) declarations in backend and frontend source files. Each entry links to its source location. File-level responsibilities are documented in [Source-code Reference](source-reference.md), and public REST behavior is documented in [API Reference](../api/README.md).")
[void]$builder.AppendLine()
[void]$builder.AppendLine('The scanner recognizes declarations written on one line. When a new declaration style is not listed here, add scanner support rather than silently leaving it undocumented.')

foreach ($group in ($entries | Group-Object File)) {
    [void]$builder.AppendLine()
    [void]$builder.AppendLine("## ``$($group.Name)``")
    [void]$builder.AppendLine()
    [void]$builder.AppendLine('| Declaration | Kind | Functionality |')
    [void]$builder.AppendLine('|---|---|---|')
    foreach ($entry in $group.Group) {
        $description = Describe-Declaration $entry.Name $entry.Kind $entry.Test
        $location = "[$($entry.Name)](../../$($entry.File):$($entry.Line))"
        [void]$builder.AppendLine("| $location | $($entry.Kind) | $(Escape-Markdown $description) |")
    }
}

[IO.File]::WriteAllText($outputPath, $builder.ToString(), [Text.UTF8Encoding]::new($false))
Write-Host "Wrote $outputPath with $($entries.Count) declarations."
